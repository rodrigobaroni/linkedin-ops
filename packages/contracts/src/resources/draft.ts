import { z } from "zod";
import { AsyncAcceptedSchema, ClassifiedErrorSchema } from "../common/async.js";
import {
  IanaTimezoneSchema,
  IsoDateTimeSchema,
  LocalDateTimeSchema,
  LocalSlotSchema,
} from "../common/datetime.js";
import { RowVersionSchema, UuidSchema } from "../common/ids.js";
import { PaginationQuerySchema } from "../common/pagination.js";
import { DraftStatusSchema } from "../enums/draft.js";
import { LanguageSchema } from "../enums/language.js";
import { DraftVersionSchema, DraftVersionSummarySchema } from "./draft-version.js";
import { PublicationSchema } from "./publication.js";
import { ScheduleSchema } from "./schedule.js";

/** Draft aggregate (`GET /drafts/{id}`, contracts.md §3.2). */
export const DraftSchema = z
  .object({
    id: UuidSchema,
    opportunityId: UuidSchema,
    status: DraftStatusSchema,
    language: LanguageSchema,
    rowVersion: RowVersionSchema,
    currentVersion: DraftVersionSchema.nullable(),
    approvedVersion: DraftVersionSchema.nullable(),
    schedule: ScheduleSchema.nullable(),
    lastPublication: PublicationSchema.nullable(),
    failureReason: ClassifiedErrorSchema.nullable(),
    needsReconciliation: z.boolean().describe("FAILED after an AMBIGUOUS publication (ADR-0003)"),
    isPrefetch: z.boolean().describe("Pre-generated by assistedPrefetchDraft and not yet adopted"),
    proposedSlot: LocalSlotSchema.nullable().describe("Suggestion, not a Schedule"),
    discardedAt: IsoDateTimeSchema.nullable(),
    discardReason: z.string().max(500).nullable(),
    createdAt: IsoDateTimeSchema,
    updatedAt: IsoDateTimeSchema,
  })
  .meta({ id: "Draft" });
export type Draft = z.infer<typeof DraftSchema>;

/** `GET /drafts` item: aggregate without nested versions, plus a version summary. */
export const DraftListItemSchema = DraftSchema.omit({
  currentVersion: true,
  approvedVersion: true,
  schedule: true,
  lastPublication: true,
})
  .extend({
    currentVersion: DraftVersionSummarySchema.nullable(),
    approvedVersionId: UuidSchema.nullable(),
    scheduledAt: IsoDateTimeSchema.nullable(),
  })
  .meta({ id: "DraftListItem" });
export type DraftListItem = z.infer<typeof DraftListItemSchema>;

export const DraftListQuerySchema = PaginationQuerySchema.extend({
  status: DraftStatusSchema.optional(),
  from: IsoDateTimeSchema.optional(),
  to: IsoDateTimeSchema.optional(),
});
export type DraftListQuery = z.infer<typeof DraftListQuerySchema>;

/** Every draft mutation carries the expected row version (contracts.md §1, `409 ROW_VERSION_MISMATCH`). */
export const DraftMutationInputSchema = z.strictObject({
  expectedRowVersion: RowVersionSchema,
});
export type DraftMutationInput = z.infer<typeof DraftMutationInputSchema>;

export const DraftRegenerateInputSchema = DraftMutationInputSchema.extend({
  instructions: z.string().trim().max(2000).optional(),
  keepHooks: z.boolean().optional(),
}).meta({ id: "DraftRegenerateInput" });
export type DraftRegenerateInput = z.infer<typeof DraftRegenerateInputSchema>;

export const DraftSubmitReviewInputSchema = DraftMutationInputSchema.meta({
  id: "DraftSubmitReviewInput",
});
export type DraftSubmitReviewInput = z.infer<typeof DraftSubmitReviewInputSchema>;

export const DraftApproveInputSchema = DraftMutationInputSchema.extend({
  versionId: UuidSchema,
}).meta({ id: "DraftApproveInput" });
export type DraftApproveInput = z.infer<typeof DraftApproveInputSchema>;

export const DraftRejectInputSchema = DraftMutationInputSchema.extend({
  versionId: UuidSchema,
  reason: z.string().trim().min(1).max(1000),
}).meta({ id: "DraftRejectInput" });
export type DraftRejectInput = z.infer<typeof DraftRejectInputSchema>;

/** `POST /drafts/{id}/schedule`: local time + IANA timezone, never a bare offset. */
export const DraftScheduleInputSchema = DraftMutationInputSchema.extend({
  versionId: UuidSchema,
  localDateTime: LocalDateTimeSchema,
  timezone: IanaTimezoneSchema,
}).meta({ id: "DraftScheduleInput" });
export type DraftScheduleInput = z.infer<typeof DraftScheduleInputSchema>;

export const DraftPublishInputSchema = DraftMutationInputSchema.extend({
  versionId: UuidSchema,
}).meta({ id: "DraftPublishInput" });
export type DraftPublishInput = z.infer<typeof DraftPublishInputSchema>;

export const DraftRetryPublicationInputSchema = DraftMutationInputSchema.meta({
  id: "DraftRetryPublicationInput",
});
export type DraftRetryPublicationInput = z.infer<typeof DraftRetryPublicationInputSchema>;

export const DraftDiscardInputSchema = DraftMutationInputSchema.extend({
  reason: z.string().trim().max(500).optional(),
}).meta({ id: "DraftDiscardInput" });
export type DraftDiscardInput = z.infer<typeof DraftDiscardInputSchema>;

/** `202` from publish / retry-publication (`id` = publication id). */
export const PublishAcceptedSchema = AsyncAcceptedSchema.extend({
  publicationId: UuidSchema,
}).meta({ id: "PublishAccepted" });
export type PublishAccepted = z.infer<typeof PublishAcceptedSchema>;
