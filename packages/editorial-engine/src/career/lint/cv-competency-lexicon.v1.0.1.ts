/*
 * cv-competency-lexicon@1.0.1: closed list of competence names (technologies, languages, frameworks, platforms,
 * tools, standards, methodologies) that a tailored CV segment may name although the base CV does not, and only
 * when a requirement the segment cites names it too (D4 entity guard; docs/editorial/cv-competency-lexicon.md).
 * Seeded by Pêndulo from Pena's pre-review (criteria C1–C7, coverage §3, deny list §4); 1.0.1 applies her item
 * by item review (cv-competency-lexicon-review.md §6). Never in the lexicon: companies, umbrella brands, certifications or credentials, ambiguous short forms
 * (only the qualified form: `Next.js`, never `Next`). `denyTerms` must never intersect the lexicon (test).
 * Changing an entry is a version bump. JSON-serializable: `JSON.stringify(CV_COMPETENCY_LEXICON)`.
 */

export type CompetencyCategory =
  | "language"
  | "data-engineering"
  | "database"
  | "analytics"
  | "ml-ai"
  | "cloud"
  | "devops"
  | "framework"
  | "protocol"
  | "practice"
  | "tool"
  | "standard";

export type CompetencyArea = "data" | "engineering" | "product" | "cross";

export interface CompetencyEntry {
  /** Canonical spelling. */
  term: string;
  /** Other spellings of the same competence (compared without case or diacritics). */
  aliases?: readonly string[];
  category: CompetencyCategory;
  areas: readonly CompetencyArea[];
}

export interface DenyGroup {
  group: string;
  /**
   * How the guard matches the terms in tailored text (always as phrases, without case or diacritics):
   * `any-case` = distinctive names, rejected even in lowercase (`nubank`); `capitalized` = names that are also
   * common words (`Via`, `Rede`, `Meta`), rejected only when written as a name; `lexicon-only` = short forms that
   * are not clients (`Spring`, `Linear`, `Make`): never matched at runtime (the closed list already rejects them as
   * names), only kept out of the lexicon by the intersection test (Pena review §6.6 R4).
   */
  match: "any-case" | "capitalized" | "lexicon-only";
  /** Names that must never be lexicon terms or aliases, nor appear in added/rewritten text (unless in the base CV). */
  terms: readonly string[];
}

export interface CompetencyLexicon {
  id: "cv-competency-lexicon";
  version: string;
  entries: readonly CompetencyEntry[];
  denyTerms: readonly DenyGroup[];
}

